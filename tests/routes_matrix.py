def route_to_regex(path_template: str) -> str:
    """`:param` -> `[^/]+` (URL-encoded), the rest of the path is literal."""
    import re

    parts = path_template.split("/")
    pattern_parts = [r"[^/]+" if part.startswith(":") else re.escape(part) for part in parts]
    return "^" + "/".join(pattern_parts) + "$"
